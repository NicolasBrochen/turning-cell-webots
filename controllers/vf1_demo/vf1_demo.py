cycle = 0
while True:
    tc = robot.getTime()
    spin(0)
    phase = "load"
    retract_to(*L.spindle_in_table(*LOAD_XY))
    move({"x": LOAD_XY[0], "y": LOAD_XY[1], "z": 0.0}, RAPID)
    clamp(False)
    doors(True)
    if cycle == 0:
        w = table_world(-0.05, 0.0, 0.08)
        shot("vises_open_empty", (w[0] + 0.10, w[1] - 0.55, w[2] + 0.35), w)
    for i in range(len(vises)):
        step(2.5)                                      # robot: pick, approach, place, release, retract
        load_part(i)
    if cycle == 0:
        w = table_world(-0.15, 0.0, 0.10)
        shot("vise1_open_part", (w[0] + 0.10, w[1] - 0.30, w[2] + 0.12), w)
    clamp(True)
    if cycle == 0:
        shot("vise1_clamped", (w[0] + 0.10, w[1] - 0.30, w[2] + 0.12), w)
    step(1.0)                                          # robot leaves the machine
    doors(False)
    probe_parts()
    tool_change(T_FACE)
    ots_check(T_FACE)
    machine(T_FACE)
    if cycle == 0:
        w = table_world(0.0, 0.0, 0.1)
        shot("overview_closed", (-0.9, -2.0, 1.75), (w[0], w[1], w[2] + 0.1))
    machine(T_SPOT)
    machine(T_DRILL)
    ots_check(T_DRILL, setting=False)
    machine(T_MILL)
    air_blast()
    phase = "unload"
    retract_to(*L.spindle_in_table(*LOAD_XY))
    move({"x": LOAD_XY[0], "y": LOAD_XY[1], "z": 0.0}, RAPID)
    purge(True)
    step(0.5)
    if cycle == 0:
        w = table_world(-0.05, 0.0, 0.10)
        shot("purge_unclamp", (w[0] + 0.28, w[1] - 0.24, w[2] + 0.16), w)
    step(1.0)
    clamp(False)
    step(0.5)
    purge(False)
    doors(True)
    for i in range(len(vises)):
        step(2.5)                                      # robot takes the finished part
        unload_part(i)
        print("VF1_DEMO  part taken out of %s" % vises[i]["cfg"]["name"])
    step(1.0)
    doors(False)
    print("VF1_DEMO cycle %d done: %.1f s (t = %.1f s)" % (cycle, robot.getTime() - tc, robot.getTime()))
    summary()
    cycle += 1
    if "cycles" in ARGS and cycle >= int(ARGS["cycles"]):
        robot.simulationQuit(0)
        step(1.0)
