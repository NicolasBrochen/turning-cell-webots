def tool_cyls(n):
    if not n:
        return []
    t = _PROBE if n == PROBE_TOOL else _TOOLS[(n - 1) % len(_TOOLS)]
    out = []
    for kind, r, z0, z1, _ in t["parts"]:
        out.append((r, z0 - r, z0 + r) if kind == "sphere" else (r, min(z0, z1), max(z0, z1)))
    return out


