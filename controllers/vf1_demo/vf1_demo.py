"""Haas VF-1 demo: robot-tended cell with two SCHUNK KSP3 pneumatic vices, a Renishaw OMP40-2 spindle probe, an OTS
tool setter and the Haas auto air gun, in a loop.

Cycle (durations close to a real machine; feeds of a 6061 aluminium part, rapids 25.4 m/min):
  doors open -> the parts are put in the vices (an "invisible hand": a robot would do it; the part nodes appear) ->
  part sensors checked, vices clamp (0.2 s stroke + pressure build-up) -> doors close -> probing with the OMP40-2
  (tool change to the probe, optical switch-on, two-touch probing of the top face and the sides of each part) ->
  tool length setting of the face mill on the OTS -> machining (face mill, spot drill, drill, broken-tool check of
  the drill on the OTS, end mill contour) -> air blast over the parts (M83 / M84) and vice purge -> vices unclamp ->
  doors open -> the parts are taken away (removed).

Device names come from protos/HaasVF1.proto (axes, doors, tool changer) and protos/SchunkKSP3.proto (vices, prefixed
"vise 1 " / "vise 2 "). Axis conventions (metres): X table, Y saddle (+ = table towards the back), 0 = table centred
under the spindle; Z head, 0 = top, negative = down. Doors: 0 = closed, + = opening. Tool changer: "carousel slide
motor" (0 = retracted, max = station pocket on the spindle axis), "carousel motor" (position (n-1)*2pi/20 brings
pocket n to the station).

Tool change (Haas umbrella, fixed pockets: tool n always goes back to pocket n), ~4 s tool to tool:
  Z up to Z_CLAMP + spindle orient -> carriage in (the station pocket catches the V-flange) -> unclamp, Z up to 0
  (tool left in the pocket) -> carousel turns to the new pocket (shortest way) -> Z down to Z_CLAMP, clamp ->
  carriage out.
Tool transfer: the PROTO holds two copies of every tool (DEF TOOL_P<n> in pocket n, DEF TOOL_S<n> in the spindle),
each on a SliderJoint; the copy not in use is parked TOOL_PARK below its seat. At clamp / unclamp both copies are at
the same place, so swapping their joint positions (Node.setJointPosition, supervisor) moves the tool seamlessly.
The controller must therefore run as a supervisor (supervisor TRUE in the world).

Vices: "clamped" / "unclamped" are read from the jaw position sensor (like the inductive switches on the SCHUNK
piston): unclamped < 0.2 mm, clamped = stopped at the contact position (clamp_at) +- 0.5 mm, beyond stroke - 0.2 mm =
closed without a part. "Part present" = "part sensor" (DistanceSensor under the part) < 30 mm.
Clearance monitor: at every step the head, spindle nose, air nozzle and current tool (cylinders, table frame) are
checked against the equipment shapes of vf1_layout.py; the part being cut / probed and the OTS disc during a tool
setting are expected contacts and are not counted. The minima are printed at the end of each cycle.
"""
