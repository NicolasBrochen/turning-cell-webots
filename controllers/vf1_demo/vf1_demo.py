def part_distance(v):
    """Depth seen by the vice part sensor (1 x 1 RangeFinder looking up between the jaws), m."""
    img = v["part_sensor"].getRangeImage()
    d = img[0] if img else float("inf")
    return d if d == d else float("inf")


