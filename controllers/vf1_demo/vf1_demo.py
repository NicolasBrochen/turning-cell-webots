def shot(name, eye, target):
    """Export the 3D view seen from eye towards target (world frame) as <shots>/<name>.jpg (only with --shots)."""
    if not SHOTS or viewpoint is None:
        return
    fx, fy, fz = (target[i] - eye[i] for i in range(3))
    n = math.sqrt(fx * fx + fy * fy + fz * fz)
    x = (fx / n, fy / n, fz / n)                       # Webots viewpoint: looks along +x, z up
    y = (-x[1], x[0], 0.0)
    ny = math.hypot(y[0], y[1]) or 1.0
    y = (y[0] / ny, y[1] / ny, 0.0)
    z = (x[1] * y[2] - x[2] * y[1], x[2] * y[0] - x[0] * y[2], x[0] * y[1] - x[1] * y[0])
    m = [[x[0], y[0], z[0]], [x[1], y[1], z[1]], [x[2], y[2], z[2]]]
    c = max(-1.0, min(1.0, (m[0][0] + m[1][1] + m[2][2] - 1) / 2))
    a = math.acos(c)
    ax = (m[2][1] - m[1][2], m[0][2] - m[2][0], m[1][0] - m[0][1])
    na = math.sqrt(sum(v * v for v in ax)) or 1.0
    viewpoint.getField("position").setSFVec3f(list(eye))
    viewpoint.getField("orientation").setSFRotation([ax[0] / na, ax[1] / na, ax[2] / na, a])
    robot.step(dt)
    robot.exportImage(os.path.join(SHOTS, name + ".jpg"), 90)
    robot.step(dt)
    print("VF1_DEMO shot %s" % name)


def table_world(xt, yt, zt):
    """World point of a table-frame point at the current X, Y (the HaasVF1 node is at the world origin)."""
    X, Y = sensors["x"].getValue(), sensors["y"].getValue()
    return (L.TABLE_TOP_XY0[0] + X + xt, L.TABLE_TOP_XY0[1] + Y + yt, TABLE_TOP + zt)


# ---- clearance monitor
allowed = set()                      # equipment shapes that may be touched now (part being cut / probed, OTS disc)
clear_min = {}                       # equipment name -> (distance, phase, t)
phase = "start"


def monitor():
    X, Y, Z = (sensors[a].getValue() for a in "xyz")
    head = L.head_shapes(X, Y, Z, tool_cyls(current))
    for s in L.shapes(with_parts=any(v["part"] for v in vises)):
        if s[1] in allowed or (s[1].endswith(" part") and not vises[int(s[1].split()[1]) - 1]["part"]):
            continue
        d = min(L.dist(h, s) for h in head)
        if s[1] not in clear_min or d < clear_min[s[1]][0]:
            clear_min[s[1]] = (d, phase, robot.getTime())
        if d < 1e-4:
            print("VF1_DEMO COLLISION %s / head-tool T%d at t = %.2f (%s)" % (s[1], current, robot.getTime(), phase))


def tool_data(n):
    return PROBE_DATA if n == PROBE_TOOL else TOOL_DATA[(n - 1) % len(TOOL_DATA) + 1]


def step(seconds=None):
    """One time step, or wait `seconds`."""
    n = 1 if seconds is None else max(1, int(round(seconds * 1000.0 / dt)))
    for _ in range(n):
        if robot.step(dt) == -1:
            raise SystemExit
        monitor()
    return True


def move(target, speed=None, timeout=60.0, tol=5e-4):
    """Send axes to target; with `speed` (m/s or rad/s) the linear axes are interpolated (they arrive together)."""
    if speed is not None:
        d = {n: abs(v - sensors[n].getValue()) for n, v in target.items()}
        dist = math.sqrt(sum(v * v for n, v in d.items() if n in ("x", "y", "z"))) or max(d.values()) or 1.0
        for n in target:
            vmax = motors[n].getMaxVelocity()
            motors[n].setVelocity(min(vmax, max(1e-4, speed * d[n] / dist)))
    for n, v in target.items():
        motors[n].setPosition(v)
    t = 0.0
    while t < timeout:
        step()
        t += dt / 1000.0
        if all(abs(sensors[n].getValue() - v) < tol for n, v in target.items()):
            return
    print("VF1_DEMO warning: timeout on %s" % target)


def transfer(n, to_spindle):
    """Swap tool n between the station pocket and the spindle (both copies coincide at this moment)."""
    copies[(n, "S")].setJointPosition(0.0 if to_spindle else -TOOL_PARK)
    copies[(n, "P")].setJointPosition(-TOOL_PARK if to_spindle else 0.0)


def orient_spindle():
    """Stop the spindle at the next multiple of 2 pi (spindle orientation before a tool change)."""
    a = spindle_sensor.getValue()
    target = 2 * math.pi * math.ceil(a / (2 * math.pi) + 0.25)
    spindle.setVelocity(40.0)
    spindle.setPosition(target)
    while abs(spindle_sensor.getValue() - target) > 1e-3:
        step()


def spin(speed):
    if speed:
        spindle.setPosition(float("inf"))
        spindle.setVelocity(speed)
    else:
        a = spindle_sensor.getValue()
        spindle.setVelocity(40.0)
        spindle.setPosition(a if a == a else 0.0)


def tool_change(new):
    """M06 T<new> with the Haas umbrella sequence; returns the duration (s)."""
    global current, phase
    if new == current:
        return 0.0
    phase = "tool change T%d" % new
    t0 = robot.getTime()
    move({"z": Z_CLAMP}, RAPID)                       # Z to the tool change height (X / Y do not move)
    orient_spindle()
    t1 = robot.getTime()
    move({"carousel slide": SLIDE}, SHUTTLE)           # carriage in: the empty pocket catches the V-flange
    if current:
        step(DRAWBAR)                                  # drawbar unclamps (air blast)
        transfer(current, to_spindle=False)
    old = current
    current = 0
    move({"z": 0.0}, RAPID)                            # spindle up, clear of the tool
    a = sensors["carousel"].getValue()
    target = (new - 1) * 2 * math.pi / POCKETS
    target += 2 * math.pi * round((a - target) / (2 * math.pi))   # shortest way
    move({"carousel": target}, CAROUSEL, tol=1e-3)
    move({"z": Z_CLAMP}, RAPID)                        # spindle down onto the new tool
    step(DRAWBAR)                                      # drawbar clamps
    transfer(new, to_spindle=True)
    current = new
    move({"carousel slide": 0.0}, SHUTTLE)             # carriage out
    t2 = robot.getTime()
    print("VF1_DEMO  M06 T%d (T%d back in pocket %d): tool to tool %.2f s, + %.2f s Z to the change height and orient"
          % (new, old, old, t2 - t1, t1 - t0))
    return t2 - t0


def z_for_tip(n, tip_z):
    """Z axis position that puts the tip of tool n at height tip_z (world)."""
    return tip_z + GROOVE_TO_NOSE + tool_data(n)[1] - NOSE_Z_TOP


def goto(xt, yt, tip_zt, speed=RAPID, tol=5e-4):
    """Move the tool tip of the current tool to table point (xt, yt, tip_zt) in a straight line."""
    X, Y = L.spindle_over(xt, yt)
    move({"x": X, "y": Y, "z": z_for_tip(current, TABLE_TOP + tip_zt)}, speed, tol=tol)


def safe_z(margin=0.03):
    """Tip height (table frame) above all the equipment and parts."""
    top = max((s[3][2] if s[0] == "box" else s[5]) for s in L.shapes(with_parts=any(v["part"] for v in vises)))
    return top + margin


def retract_to(xt, yt, margin=0.03):
    """Up to the safe height, rapid over (xt, yt) at that height."""
    X, Y, Z = (sensors[a].getValue() for a in "xyz")
    zs = z_for_tip(current, TABLE_TOP + safe_z(margin))
    if Z < zs:
        move({"z": zs}, RAPID)
    X, Y = L.spindle_over(xt, yt)
    move({"x": X, "y": Y}, RAPID)


def doors(opening):
    global phase
    phase = "doors"
    move({"door left": 0.4 if opening else 0.0, "door right": 0.4 if opening else 0.0}, DOOR_SPEED)
    print("VF1_DEMO doors %s (t = %.1f s)" % ("open" if opening else "closed", robot.getTime()))


# ---- vices and parts
PART_NODE = ('DEF %s Solid { translation 0 0 %.4f name "part" children [ Shape { appearance PBRAppearance { '
             'baseColor 0.80 0.82 0.85 roughness 0.3 metalness 0.9 } geometry Box { size %.4f %.4f %.4f } } ] '
             'boundingObject Box { size %.4f %.4f %.4f } }')


def part_centre(v):
    return v["cfg"]["x"], v["cfg"]["y"]


def load_part(i):
    v = vises[i]
    px, py, pz = L.PART
    wp = v["node"].getField("workpiece")
    # vice frame: x = clamping direction (table y), y = table -x
    wp.importMFNodeFromString(-1, PART_NODE % ("PART_%d" % (i + 1), pz / 2, py, px, pz, py, px, pz))
    v["part"] = wp.getMFNode(-1)
    step(0.2)
    d = part_distance(v)
    print("VF1_DEMO  part put in %s: part sensor %.1f mm -> %s" % (v["cfg"]["name"], d * 1000,
                                                                  "PART PRESENT" if d < 0.03 else "NO PART"))
    return d < 0.03


def unload_part(i):
    v = vises[i]
    wp = v["node"].getField("workpiece")
    while wp.getCount():
        wp.removeMF(-1)
    v["part"] = None


def vise_state(v):
    p = v["sensor"].getValue()
    if p < 2e-4:
        return "unclamped"
    if p > v["stroke"] - 2e-4:
        return "closed without part (fault)"
    if abs(p - v["clamp_at"]) < 5e-4:
        return "clamped"
    return "moving"


def clamp(close):
    """Clamp (close = True) or unclamp all the vices; the jaws stop on the part (contact at clamp_at)."""
    global phase
    phase = "vices"
    t0 = robot.getTime()
    for v in vises:
        target = (v["clamp_at"] if part_distance(v) < 0.03 else v["stroke"]) if close else 0.0
        v["target"] = target
        v["motor"].setPosition(target)
    while any(abs(v["sensor"].getValue() - v["target"]) > 2e-5 for v in vises):
        step()
    t1 = robot.getTime()
    step(0.3)                                          # pressure build-up / switch debounce
    for v in vises:
        print("VF1_DEMO  %s %s: jaw %.2f mm (stroke %.2f s) -> %s" % (
            v["cfg"]["name"], "clamp" if close else "unclamp", v["sensor"].getValue() * 1000, t1 - t0, vise_state(v)))


# ---- probing (Renishaw OMP40-2) and tool setting (OTS)
def led(on_colour, what="probe"):
    if what == "probe":
        me.getField("probeLedColor").setSFColor(on_colour)
    else:
        ots.getField("ledColor").setSFColor(on_colour)


def touch(contact, direction, what="probe"):
    """Two-touch move: `contact` = ball centre (probe) or tool tip (OTS) at contact, table frame; direction of the
    probing move (unit, table frame). Returns the contact point."""
    c, d = contact, direction
    off = PROBE_BALL_R if what == "probe" else 0.0

    def tip(k):                                       # tip target at distance k before the contact
        return c[0] - d[0] * k, c[1] - d[1] * k, c[2] - d[2] * k - off

    goto(*tip(0.005), speed=PROBE_POS, tol=1e-4)
    goto(*tip(0.0), speed=PROBE_FAST, tol=5e-5)        # first touch
    led(RED, what)
    if shot_next:
        w = table_world(c[0], c[1], c[2])
        shot(shot_next.pop(0), (w[0] + 0.16, w[1] - 0.30, w[2] + 0.07), (w[0], w[1], w[2] + 0.03))
    step(0.1)
    goto(*tip(0.002), speed=PROBE_POS, tol=5e-5)       # back off
    led(GREEN, what)
    goto(*tip(0.0), speed=PROBE_SLOW, tol=2e-5)        # second, slow touch (measurement)
    led(RED, what)
    step(0.1)
    goto(*tip(0.005), speed=PROBE_POS, tol=1e-4)
    led(GREEN, what)
    return c


shot_next = []


def probe_parts():
    global phase, allowed
    tool_change(PROBE_TOOL)
    if cycle == 0:
        w = table_world(*L.spindle_in_table(sensors["x"].getValue(), sensors["y"].getValue()), 0.45)
        shot("probe_in_spindle", (w[0] + 0.35, w[1] - 0.45, w[2] + 0.05), (w[0], w[1], w[2] + 0.02))
    phase = "probing"
    led(GREEN)                                         # optical switch-on (M-code), probe LEDs flash green
    step(0.5)
    if cycle == 0:
        shot("omm2_receiver", (0.12, -0.62, 1.42), (0.45, -0.45, 1.70))
    r = PROBE_BALL_R
    for k, v in enumerate(vises):
        cx, cy = part_centre(v)
        top = v["part_top"]
        allowed = {v["cfg"]["name"] + " part"}
        retract_to(cx, cy)
        z = touch((cx, cy, top + r), (0, 0, -1))
        print("VF1_DEMO  probe %s: top face z = %.3f mm (table)" % (v["cfg"]["name"], (z[2] - r) * 1000))
        sides = [(-1, 0), (1, 0)] + ([(0, -1), (0, 1)] if k == 0 else [])
        if k == 0 and cycle == 0:
            shot_next.append("probe_side_touch")
        found = []
        for sx, sy in sides:
            hx, hy = L.PART[0] / 2 + r, L.PART[1] / 2 + r
            start = (cx + sx * (hx + 0.008), cy + sy * (hy + 0.008))
            zt = top - 0.008                            # ball centre 8 mm below the top face
            goto(start[0], start[1], top + 0.01, speed=RAPID)
            goto(start[0], start[1], zt - r, speed=PROBE_POS)
            p = touch((cx + sx * hx, cy + sy * hy, zt), (-sx, -sy, 0))
            found.append(p)
            goto(start[0], start[1], zt - r, speed=PROBE_POS)
            goto(start[0], start[1], top + 0.01, speed=RAPID)
        xs = [p[0] for p, (sx, sy) in zip(found, sides) if sx]
        msg = "centre x %.3f mm" % (sum(xs) / 2 * 1000)
        if k == 0:
            ys = [p[1] for p, (sx, sy) in zip(found, sides) if sy]
            msg += ", centre y %.3f mm, width %.3f mm" % (sum(ys) / 2 * 1000, (ys[1] - ys[0] - 2 * r) * 1000)
        print("VF1_DEMO  probe %s: %s, length %.3f mm" % (v["cfg"]["name"], msg, (xs[1] - xs[0] - 2 * r) * 1000))
    allowed = set()
    retract_to(*part_centre(vises[-1]))
    led(OFF)                                           # probe switched off
    print("VF1_DEMO probing done (t = %.1f s)" % robot.getTime())


def ots_check(n, setting=True):
    """Tool length setting (or broken tool check) of tool n on the OTS disc."""
    global phase, allowed
    phase = "OTS T%d" % n
    o = L.OTS
    rtip = min(tool_cyls(n), key=lambda c: c[1])[0]   # radius of the lowest part of the tool
    off = rtip - 0.004 if rtip > o["disc_r"] else 0.0  # large tools: the cutting edge over the disc, spindle reversed
    allowed = {"OTS disc"}
    retract_to(o["x"] - off, o["y"])
    led(GREEN, "ots")
    if off:
        spin(-30.0)
    if cycle == 0 and setting:
        shot_next.append("ots_touch")
    touch((o["x"] - off, o["y"], o["disc_top"]), (0, 0, -1), what="ots")
    spin(0)
    led(OFF, "ots")
    allowed = set()
    retract_to(o["x"] - off, o["y"])
    print("VF1_DEMO  OTS %s T%d: length %.3f mm below the gauge line (t = %.1f s)"
          % ("tool setting" if setting else "broken tool check, OK", n, (tool_data(n)[1] - GROOVE_TO_NOSE) * 1000,
             robot.getTime()))


# ---- simulated machining
def add_feature(v, kind, x, y, r, depth):
    """Visual: dark disc (hole) / ring on the part top (vice frame of the part: x = table y, y = table -x)."""
    if v["part"] is None:
        return
    pz = L.PART[2]
    v["part"].getField("children").importMFNodeFromString(
        -1, 'Pose { translation %.4f %.4f %.4f children [ Shape { appearance PBRAppearance { baseColor 0.15 0.15 '
            '0.17 roughness 0.6 metalness 0.5 } geometry Cylinder { height 0.0006 radius %.4f subdivision 16 } } ] }'
            % (y, -x, pz / 2 + 0.0003 - 0.0, r))


def machine(n):
    global phase, allowed
    tool_change(n)
    kind, _, speed = tool_data(n)
    phase = "machining T%d" % n
    spin(speed)
    t0 = robot.getTime()
    for v in vises:
        cx, cy = part_centre(v)
        top = v["part_top"]
        allowed = {v["cfg"]["name"] + " part"}
        px, py = L.PART[0] / 2, L.PART[1] / 2
        if kind == "face":                             # one pass of the D63 face mill, 0.5 mm deep
            x0, x1 = cx - px - 0.040, cx + px + 0.040
            retract_to(x0, cy)
            goto(x0, cy, top - 0.0005, speed=RAPID)
            goto(x1, cy, top - 0.0005, speed=FEED_FACE)
            retract_to(x1, cy)
        elif kind == "drill":                          # spot drill 3 mm / drill 20 mm, two holes
            depth = 0.020 if n == T_DRILL else 0.003
            feed = FEED_DRILL if n == T_DRILL else FEED_SPOT
            for hx in (-0.015, 0.015):
                retract_to(cx + hx, cy)
                goto(cx + hx, cy, top + 0.003, speed=RAPID)
                goto(cx + hx, cy, top - depth, speed=feed)
                goto(cx + hx, cy, top + 0.003, speed=RAPID)
                add_feature(v, "hole", hx, 0.0, 0.0045 if n == T_DRILL else 0.003, depth)
        else:                                          # end mill D12: contour 3 mm deep around the part
            r = 0.006
            ex, ey = px + r, py + r
            path = [(cx - ex, cy - ey - 0.010), (cx - ex, cy + ey), (cx + ex, cy + ey), (cx + ex, cy - ey),
                    (cx - ex - 0.010, cy - ey)]
            retract_to(*path[0])
            goto(path[0][0], path[0][1], top - 0.003, speed=RAPID)
            for x, y in path[1:]:
                goto(x, y, top - 0.003, speed=FEED_MILL)
            retract_to(*path[-1])
        allowed = set()
    print("VF1_DEMO  T%d %s: %.1f s (t = %.1f s)" % (n, kind, robot.getTime() - t0, robot.getTime()))


def air_blast():
    """M83 auto air gun over both parts, then vice purge during unclamping."""
    global phase
    phase = "air blast"
    spin(30.0)                                         # slow spindle: throws the chips off the tool too
    cx0, cy0 = part_centre(vises[0])
    retract_to(cx0 - 0.05, cy0 + 0.04, margin=0.035)
    me.getField("airBlastTransparency").setSFFloat(0.55)   # M83
    t0 = robot.getTime()
    if cycle == 0:
        step(0.3)
        w = table_world(cx0 - 0.05, cy0 + 0.04, 0.12)
        shot("air_blast", (w[0] + 0.30, w[1] - 0.35, w[2] + 0.12), (w[0], w[1], w[2] + 0.02))
    for v in vises:
        cx, cy = part_centre(v)
        for x, y in ((cx - 0.05, cy + 0.04), (cx + 0.05, cy + 0.04), (cx + 0.05, cy - 0.04), (cx - 0.05, cy - 0.04)):
            X, Y = L.spindle_over(x, y)
            move({"x": X, "y": Y}, 0.15)
    me.getField("airBlastTransparency").setSFFloat(1.0)    # M84
    spin(0)
    print("VF1_DEMO  M83/M84 air blast %.1f s" % (robot.getTime() - t0))


def purge(on):
    for v in vises:
        v["node"].getField("purgeTransparency").setSFFloat(0.5 if on else 1.0)


def summary():
    print("VF1_DEMO clearance minima this cycle (head, spindle nose, air nozzle, tool vs equipment; expected "
          "contacts excluded):")
    for k, (d, ph, t) in sorted(clear_min.items(), key=lambda kv: kv[1][0])[:8]:
        print("VF1_DEMO    %-20s %6.1f mm  (%s, t = %.1f s)" % (k, d * 1000, ph, t))
    clear_min.clear()


