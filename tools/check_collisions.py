#!/usr/bin/env python3
"""Offline collision check of the robot cycle (no Webots needed).

Replays the robot jobs exactly as in the simulation (the steps are generated by cell_plc.py, the joint trajectories
by ur_tending.py: same IK, same seeds, same linear interpolation) and measures the clearance between the robot (links
from UR10e.proto, F/T sensor, bent bracket, grippers, fingers, carried parts) and the cell (collision volumes exported
by tools/gen_world.py into worlds/obstacles.json: lathes, doors, chucks and jaws, turrets, table, crates, dividers,
parts in the crates, robot pedestal). Robot self-collisions (tool and carried parts against the arm) are checked too.

    uv run --no-project --with numpy tools/check_collisions.py       # (or python3 with numpy installed)
    ... -v                                                         # + every colliding sample
Exit code 1 when a collision (clearance < 0) is found.
"""
