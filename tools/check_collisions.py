WARN = 0.015
ROBOT_Z = 0.80


# ---------------------------------------------------------------- small linear algebra
def tf(T, p):
    return [T[i][0] * p[0] + T[i][1] * p[1] + T[i][2] * p[2] + T[i][3] for i in range(3)]


def rotm(rot):
    if not rot:
        return [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
    x, y, z, a = rot
    n = math.sqrt(x * x + y * y + z * z)
    x, y, z = x / n, y / n, z / n
    c, s, C = math.cos(a), math.sin(a), 1 - math.cos(a)
    return [[c + x * x * C, x * y * C - z * s, x * z * C + y * s], [y * x * C + z * s, c + y * y * C, y * z * C - x * s],
            [z * x * C - y * s, z * y * C + x * s, c + z * z * C]]


def h4(R, p):
    return [R[0] + [p[0]], R[1] + [p[1]], R[2] + [p[2]], [0, 0, 0, 1]]


# ---------------------------------------------------------------- robot geometry as sphere sets
def capsule(p0, p1, r):
    n = max(1, int(math.ceil(math.dist(p0, p1) / (0.7 * r))))
    return [([p0[i] + (p1[i] - p0[i]) * k / n for i in range(3)], r) for k in range(n + 1)]


def cyl_shape(r, h, pos, axis):
    e = [0, 0, 0]
    e["xyz".index(axis)] = max(0.0, h / 2 - 0.3 * r)
    return capsule([pos[i] - e[i] for i in range(3)], [pos[i] + e[i] for i in range(3)], r)


def box_shape(size, pos, rot=None):
    R = rotm(rot)
    k = min(range(3), key=lambda i: size[i])
    r = max(size[k] / 2, 0.012)        # thin plates: 12 mm spheres (conservative by a few mm)
    others = [i for i in range(3) if i != k]
    axes = []
    for i in others:
        half = max(0.0, size[i] / 2 - r * 0.7)
        n = max(1, int(math.ceil(2 * half / r)))
        axes.append([-half + 2 * half * j / n for j in range(n + 1)] if half > 0 else [0.0])
    pts = []
    for u in axes[0]:
        for v in axes[1]:
            loc = [0.0, 0.0, 0.0]
            loc[others[0]], loc[others[1]] = u, v
            pts.append(([pos[i] + sum(R[i][j] * loc[j] for j in range(3)) for i in range(3)], r))
    return pts


# UR10e collision shapes (UR10e.proto), in each link frame: (name, spheres)
LINKS = [
    [cyl_shape(0.077, 0.183, (0, 0, 0), "z"), cyl_shape(0.076, 0.093, (0, 0.05, 0), "y")],
    [cyl_shape(0.058, 0.463, (0, 0, 0.33), "z"), cyl_shape(0.076, 0.1, (0, 0, 0.06), "z"),
     cyl_shape(0.077, 0.183, (0, 0, 0), "y"), cyl_shape(0.061, 0.149, (0, -0.005, 0.612), "y")],
    [cyl_shape(0.047, 0.49, (0, 0, 0.307), "z"), cyl_shape(0.046, 0.129, (0, 0.009, 0.57), "y"),
     cyl_shape(0.058, 0.05, (0, 0.06, 0), "y"), cyl_shape(0.057, 0.03, (0, 0, 0.05), "z")],
    [cyl_shape(0.045, 0.075, (0, 0.095, 0), "y"), cyl_shape(0.048, 0.126, (0, 0.134, 0.007), "z")],
    [cyl_shape(0.047, 0.12, (0, 0.007, 0.1195), "y"), cyl_shape(0.046, 0.043, (0, 0, 0.0805), "z")],
    [cyl_shape(0.045, 0.048, (0, 0.086, 0), "y")],
]
LINK_NAMES = ["shoulder", "upper_arm", "forearm", "wrist_1", "wrist_2", "wrist_3"]
LINKS = [sum(sh, []) for sh in LINKS]

GEO = json.load(open(os.path.join(ROOT, "worlds", "obstacles.json")))
TOOL = []                                         # toolSlot frame
for it in GEO["tool"]:
    if it["kind"] == "box":
        TOOL += box_shape(it["dims"], it["pos"], it["rot"])
    else:
        TOOL += cyl_shape(it["dims"][0], it["dims"][1], it["pos"], "y")
FINGERS = {}                                      # toolSlot frame, open fingers of each gripper
for g in (1, 2):
    pts = []
    for side in (1, -1):
        pts += box_shape((DG.FINGER_L, 0.03, 0.012), (DG.FINGER_X0 + DG.FINGER_L / 2, 0, 0.045 * side))
    th = DG.THETA[g]
    R = rotm((0, 0, 1, th))
    fc = DG.FACE[g]
    FINGERS[g] = [([fc[i] + sum(R[i][j] * p[j] for j in range(3)) for i in range(3)], r) for p, r in pts]


def part_spheres(g):
    """Carried part (TCP frame of gripper g): from 10 mm behind the TCP to 80 mm beyond, along TCP z."""
    r = PLC.PART_R
    return capsule([0, 0, -PLC.GRIP_FROM_BACK + r], [0, 0, PLC.PART_L - PLC.GRIP_FROM_BACK - r], r)


PARTS = {g: part_spheres(g) for g in (1, 2)}


# ---------------------------------------------------------------- obstacles
class Obstacle:
    def __init__(self, d):
        self.owner, self.tag, self.kind = d["owner"], d["tag"], d["kind"]
        self.c, self.R, self.dims = d["c"], d["R"], d["dims"]
        self.cell = d.get("cell")
        if self.kind == "box":
            self.h = [v / 2 for v in self.dims]
            self.rad = math.sqrt(sum(v * v for v in self.h))
        else:
            self.rad = math.hypot(self.dims[0], self.dims[1] / 2)

    def dist(self, p):
        d = [p[i] - self.c[i] for i in range(3)]
        loc = [self.R[0][i] * d[0] + self.R[1][i] * d[1] + self.R[2][i] * d[2] for i in range(3)]   # R^T d
        if self.kind == "box":
            q = [abs(loc[i]) - self.h[i] for i in range(3)]
        else:
            r, h = self.dims
            q = [math.hypot(loc[0], loc[1]) - r, abs(loc[2]) - h / 2]
        out = math.sqrt(sum(max(v, 0.0) ** 2 for v in q))
        return out if out > 0 else max(q)


OBST = [Obstacle(d) for d in GEO["obstacles"]]


# ---------------------------------------------------------------- replay of the robot jobs
class Replay(UR.Tending):
    """ur_tending.Tending without Webots: same IK / interpolation code, fixed base, no devices."""

    def __init__(self):
        self.errors = []
        self.q_cmd = list(UR.Q_HOME)
        self.override = 1.0

    def base_T(self):
        return [[math.cos(DG.ROBOT_YAW), -math.sin(DG.ROBOT_YAW), 0, 0], [math.sin(DG.ROBOT_YAW), math.cos(DG.ROBOT_YAW), 0, 0], [0, 0, 1, ROBOT_Z], [0, 0, 0, 1]]

    def send(self, **m):
        if m.get("evt") == "error":
            self.errors.append(m["msg"])


def make_plc():
    plc = object.__new__(PLC.CellPLC)
    plc.lathes = {}
    for n in ("A", "B"):
        lt = object.__new__(PLC.Lathe)
        lt.name = n
        lt.x0, lt.yaw = PLC.LATHES[n]
        lt.R = PLC.rz(lt.yaw)
        lt.part = "PART_X"
        plc.lathes[n] = lt
    return plc


def samples(rb, st):
    """Yield joint configurations along one step (same code path as the controller)."""
    t = st["t"]
    q0 = list(rb.q_cmd)
    if t in ("joint", "home"):
        q1 = list(st.get("_q", UR.Q_HOME)) if t == "home" else rb.solve(rb.target(st), st["g"], q0, st.get("seed"))
        if q1 is None:
            rb.errors.append("IK failed (joint) %s" % st["p"])
            return
        n = max(2, int(max(abs(a - b) for a, b in zip(q0, q1)) / 0.04))
        for k in range(n + 1):
            s = UR.quintic(k / n)
            rb.q_cmd = [a + (b - a) * s for a, b in zip(q0, q1)]
            yield rb.q_cmd
    elif t in ("lin", "force"):
        p0, R0 = rb.tcp_world(st["g"], q0)
        if t == "lin":
            Tg = UR.pose(st["p"], st["a"], st["x"])
            p1, R1 = [Tg[i][3] for i in range(3)], UR.m3(Tg)
        else:
            p1 = [p0[i] + st["dir"][i] * (st["contact"] + 0.001) for i in range(3)]
            R1 = R0
        aa = UR.axis_angle(UR.mmul3(R1, UR.tr3(R0)))
        st.update(_p0=p0, _p1=p1, _R0=R0, _aa=aa)
        n = max(2, int(max(math.dist(p0, p1) / 0.015, abs(aa[3]) / 0.04)))
        for k in range(n + 1):
            rb.q_cmd = rb.cart_q(st, k / n)
            yield rb.q_cmd


def robot_parts(q, held):
    """World sphere sets: (name, spheres, link index)."""
    B = [[math.cos(DG.ROBOT_YAW), -math.sin(DG.ROBOT_YAW), 0, 0], [math.sin(DG.ROBOT_YAW), math.cos(DG.ROBOT_YAW), 0, 0], [0, 0, 1, ROBOT_Z], [0, 0, 0, 1]]
    Fr = [mat_mul(B, T) for T in fk_frames(q)]
    out = []
    for i, sph in enumerate(LINKS):
        out.append((LINK_NAMES[i], [(tf(Fr[i], p), r) for p, r in sph], i))
    S = Fr[6]
    out.append(("bent bracket + grippers", [(tf(S, p), r) for p, r in TOOL], 6))
    for g in (1, 2):
        out.append(("fingers %d" % g, [(tf(S, p), r) for p, r in FINGERS[g]], 6))
        if held.get(g):
            T = mat_mul(S, UR.TCP[g])
            out.append(("part in gripper %d" % g, [(tf(T, p), r) for p, r in PARTS[g]], 7))
    return out


def bound(sph):
    c = [sum(p[i] for p, _ in sph) / len(sph) for i in range(3)]
    return c, max(math.dist(c, p) + r for p, r in sph)


import numpy as np  # noqa: E402

_BOX = [o for o in OBST if o.kind == "box"]
_CYL = [o for o in OBST if o.kind == "cyl"]
_ORDER = _BOX + _CYL
_C = np.array([o.c for o in _ORDER])
_R = np.array([o.R for o in _ORDER])
_HB = np.array([o.h for o in _BOX])
_CR = np.array([o.dims for o in _CYL])
_NB = len(_BOX)
_RAD = np.array([o.rad for o in _ORDER])


def _obstacle_mask(names, served, ignore_cells):
    """Pairs (robot part, obstacle) to check, for the current job."""
    m = np.ones((len(names), len(_ORDER)), bool)
    for j, ob in enumerate(_ORDER):
        skip_all = ((ob.tag == "part" and tuple(ob.cell) in ignore_cells)
                    or (ob.tag == "door_closed" and served and ob.owner.startswith("TOUR_" + served))
                    or (ob.tag == "door_open" and not (served and ob.owner.startswith("TOUR_" + served))))
        for i, name in enumerate(names):
            if skip_all or (name.startswith("part") and ob.tag in ("chuck", "jaws", "crate_floor")) \
                    or (name.startswith("fingers") and ob.tag == "crate_floor"):
                m[i, j] = False
    return m


_MASKS = {}


def check(q, held, ctx, ignore_cells, served):
    """Smallest clearances of this configuration: list of (clearance, robot part, obstacle)."""
    parts = robot_parts(q, held)
    names = [p[0] for p in parts]
    key = (tuple(names), served, tuple(sorted(ignore_cells)))
    if key not in _MASKS:
        _MASKS[key] = _obstacle_mask(names, served, ignore_cells)
    mask = _MASKS[key]
    P = np.array([p for _, sph, _ in parts for p, _ in sph])
    r = np.array([r for _, sph, _ in parts for _, r in sph])
    gid = np.repeat(np.arange(len(parts)), [len(sph) for _, sph, _ in parts])
    lo, hi = P.min(0) - 0.1, P.max(0) + 0.1
    near = np.nonzero(np.all((_C + _RAD[:, None] > lo) & (_C - _RAD[:, None] < hi), axis=1))[0]
    nb = near[near < _NB]
    nc = near[near >= _NB]
    res = []
    D = []
    if len(nb):
        loc = np.einsum("nmj,mji->nmi", P[:, None, :] - _C[None, nb], _R[nb])
        qb = np.abs(loc) - _HB[None, nb]
        D.append(np.linalg.norm(np.maximum(qb, 0), axis=2) + np.minimum(qb.max(axis=2), 0))
    if len(nc):
        lc = np.einsum("nmj,mji->nmi", P[:, None, :] - _C[None, nc], _R[nc])
        cr = _CR[nc - _NB]
        qc = np.stack([np.hypot(lc[..., 0], lc[..., 1]) - cr[None, :, 0], np.abs(lc[..., 2]) - cr[None, :, 1] / 2], 2)
        D.append(np.linalg.norm(np.maximum(qc, 0), axis=2) + np.minimum(qc.max(axis=2), 0))
    if D:
        cols = np.concatenate([nb, nc])
        D = np.concatenate(D, 1) - r[:, None]
        for i in range(len(parts)):
            Di = D[gid == i].min(axis=0)
            for k in np.nonzero((Di < WARN) & mask[i][cols])[0]:
                ob = _ORDER[cols[k]]
                res.append((float(Di[k]), names[i], "%s (%s)" % (ob.owner, ob.tag)))
    # self-collision: tool, fingers and carried parts against the arm (links not joint-adjacent to the tool)
    for i, (name, sph, li) in enumerate(parts):
        if li < 6:
            continue
        for j, (lname, lsph, lj) in enumerate(parts):
            if lj > 3 or (li == 7 and lj >= 5):
                continue
            A, B = P[gid == i], P[gid == j]
            dd = (np.linalg.norm(A[:, None] - B[None], axis=2) - r[gid == i][:, None] - r[gid == j][None]).min()
            if dd < WARN:
                res.append((float(dd), name, "UR10e " + lname))
    return res


def cycle(plc):
    """Job sequence of the cycle: (label, steps, held before/after markers handled by the step types)."""
    jobs = []
    for i in range(12):
        L = "A" if i % 2 == 0 else "B"
        jobs.append(("pick blank cell %d" % (i + 1), plc.crate_steps_pick(1, "BRUTS", i, "PART"), ("BRUTS", i)))
        jobs.append(("lathe %s %s" % (L, "load" if i < 2 else "unload + load"), plc.lathe_steps(L, i >= 2), None))
        if i >= 2:
            jobs.append(("finished part -> cell %d" % (i - 1), plc.crate_steps_place(2, "FINIES", i - 2), ("FINIES", i - 2)))
    return jobs


def run(verbose=False, quiet=False):
    plc = make_plc()
    rb = Replay()
    held = {1: False, 2: False}
    worst = {}
    n_coll = 0
    rb.q_cmd = [0.0] * 6                       # start-up from the zero pose (see ur_tending.run)
    for qh in UR.start_path(0.0):
        for q in samples(rb, dict(t="home", _q=qh)):
            for d, a, b in check(q, held, "start-up", set(), ""):
                key = ("start-up", 0, "home", a, b)
                if key not in worst or d < worst[key][0]:
                    worst[key] = (d, [round(v, 3) for v in q])
    for label, steps, cell in cycle(plc)[:int(os.environ.get("JOBS", "999"))]:
        served = label.split()[1] if label.startswith("lathe") else ""
        ignore = {tuple(cell)} if cell else set()
        for k, st in enumerate(steps):
            if st["t"] == "grip":
                held[st["g"]] = True
            elif st["t"] == "open":
                held[st["g"]] = False
            for q in samples(rb, st):
                for d, a, b in check(q, held, label, ignore, served):
                    key = (label.split(" cell")[0], k, st["t"], a, b)
                    if key not in worst or d < worst[key][0]:
                        worst[key] = (d, [round(v, 3) for v in q])
                    if verbose and d < 0:
                        print("  %-28s step %2d %-5s %-26s %-36s %+.3f" % (label, k, st["t"], a, b, d))
    errs = sorted(set(rb.errors))
    if not quiet:
        for e in errs:
            print("IK:", e)
        rows = sorted(worst.items(), key=lambda kv: kv[1][0])
        for (lab, k, t, a, b), (d, q) in rows[:60]:
            flag = "COLLISION" if d < 0 else "close"
            print("%-9s %+.3f m  %-28s step %2d %-5s %-26s <-> %s" % (flag, d, lab, k, t, a, b))
        n_coll = sum(1 for v in worst.values() if v[0] < 0)
        print("\n%d colliding pairs, %d pairs closer than %.0f mm, %d IK errors" % (
            n_coll, sum(1 for v in worst.values() if 0 <= v[0] < WARN), WARN * 1000, len(errs)))
    return worst, errs


if __name__ == "__main__":
    w, e = run("-v" in sys.argv)
    sys.exit(1 if any(v[0] < 0 for v in w.values()) or e else 0)
